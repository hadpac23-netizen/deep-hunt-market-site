-- BOOM Professional Eval Lineage
-- SOURCE ONLY until explicitly applied. No Production, provider, payment, supplier or publish activation.
-- Pins the exact dataset + prompt + eval run + source commit used for a measured result.

create table if not exists public.hunt_boom_eval_dataset_versions (
  id bigint generated by default as identity primary key,
  dataset_key text not null,
  version integer not null check (version > 0),
  suite_id bigint not null references public.hunt_boom_eval_suites(id) on delete restrict,
  case_count integer not null check (case_count >= 0),
  case_manifest_hash text not null,
  source_ref text,
  source_commit text,
  status text not null default 'frozen'
    check (status in ('draft','frozen','retired')),
  metadata jsonb not null default '{}'::jsonb,
  owner_approval_required boolean not null default true,
  created_at timestamptz not null default now(),
  frozen_at timestamptz,
  unique (dataset_key,version)
);

create unique index if not exists hunt_boom_eval_dataset_versions_hash_uidx
  on public.hunt_boom_eval_dataset_versions(dataset_key,case_manifest_hash)
  where status='frozen';

create index if not exists hunt_boom_eval_dataset_versions_suite_idx
  on public.hunt_boom_eval_dataset_versions(suite_id,version desc);

create table if not exists public.hunt_boom_eval_lineage (
  id bigint generated by default as identity primary key,
  eval_run_id bigint not null references public.hunt_boom_eval_runs_v2(id) on delete restrict,
  suite_id bigint not null references public.hunt_boom_eval_suites(id) on delete restrict,
  dataset_version_id bigint not null references public.hunt_boom_eval_dataset_versions(id) on delete restrict,
  prompt_version_id bigint references public.hunt_boom_prompt_versions(id) on delete restrict,
  candidate_ref text not null,
  source_commit text,
  evidence jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique (eval_run_id)
);

create index if not exists hunt_boom_eval_lineage_dataset_idx
  on public.hunt_boom_eval_lineage(dataset_version_id,eval_run_id);
create index if not exists hunt_boom_eval_lineage_prompt_idx
  on public.hunt_boom_eval_lineage(prompt_version_id,eval_run_id)
  where prompt_version_id is not null;

alter table public.hunt_boom_eval_dataset_versions enable row level security;
alter table public.hunt_boom_eval_lineage enable row level security;

revoke all on table public.hunt_boom_eval_dataset_versions from anon, authenticated;
revoke all on table public.hunt_boom_eval_lineage from anon, authenticated;

grant select, insert on table public.hunt_boom_eval_dataset_versions to authenticated;
grant select, insert on table public.hunt_boom_eval_lineage to authenticated;
grant all on table public.hunt_boom_eval_dataset_versions to service_role;
grant all on table public.hunt_boom_eval_lineage to service_role;

drop policy if exists "Admins read hunt_boom_eval_dataset_versions" on public.hunt_boom_eval_dataset_versions;
create policy "Admins read hunt_boom_eval_dataset_versions"
on public.hunt_boom_eval_dataset_versions for select to authenticated
using (
  exists (
    select 1 from public.profiles p
    where p.id=(select auth.uid()) and p.is_admin=true
  )
);

drop policy if exists "Admins append hunt_boom_eval_dataset_versions" on public.hunt_boom_eval_dataset_versions;
create policy "Admins append hunt_boom_eval_dataset_versions"
on public.hunt_boom_eval_dataset_versions for insert to authenticated
with check (
  exists (
    select 1 from public.profiles p
    where p.id=(select auth.uid()) and p.is_admin=true
  )
);

