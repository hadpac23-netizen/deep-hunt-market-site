comment on table public.hunt_boom_eval_dataset_versions is
  'Versioned frozen eval dataset manifests. No authenticated UPDATE/DELETE grants.';
comment on table public.hunt_boom_eval_lineage is
  'Append-only link from an eval run to the exact suite, dataset version, prompt version and source commit.';
