drop policy if exists "Admins append hunt_boom_eval_lineage" on public.hunt_boom_eval_lineage;
create policy "Admins append hunt_boom_eval_lineage"
on public.hunt_boom_eval_lineage for insert to authenticated
with check (
  exists (
    select 1 from public.profiles p
    where p.id=(select auth.uid()) and p.is_admin=true
  )
